class AutoUploadTest(unittest.TestCase):
    """只有发行商代传的 YouTube 自动投稿的曲子不收（用户 2026-10 要求）。

    实测 S/950828（ワープループ）：唯一的 PV 是 `author = "Yunosuke - Topic"`、
    简介 `Provided to YouTube by NexTone Inc. … Auto-generated by YouTube.`。
    """

    TOPIC = {"service": "Youtube", "author": "Yunosuke - Topic",
             "description": "Provided to YouTube by NexTone Inc.\n\nワープループ\n\n"
                            "Auto-generated by YouTube."}
    REAL = {"service": "NicoNicoDouga", "author": "雄之助", "description": "新曲です"}

    def test_is_auto_upload(self):
        self.assertTrue(pt.is_auto_upload(self.TOPIC))
        self.assertTrue(pt.is_auto_upload({"author": "雄之助 - Topic"}))
        self.assertTrue(pt.is_auto_upload({"description": "Provided to YouTube by X"}))
        self.assertTrue(pt.is_auto_upload({"description": "Auto-generated by YouTube."}))
        self.assertFalse(pt.is_auto_upload(self.REAL))
        self.assertFalse(pt.is_auto_upload({}))

    def test_has_real_pv(self):
        self.assertFalse(pt.has_real_pv({"pvs": [self.TOPIC]}))
        self.assertTrue(pt.has_real_pv({"pvs": [self.TOPIC, self.REAL]}))   # 混着就保留
        self.assertTrue(pt.has_real_pv({"pvs": [self.REAL]}))
        self.assertTrue(pt.has_real_pv({}))                                   # 没信息就不删

    def test_fetch_songs_skips_auto_upload_only_songs(self):
        payload = {"items": [
            {**SONG_ITEM, "id": 1, "defaultName": "ワープループ", "pvs": [self.TOPIC]},
            {**SONG_ITEM, "id": 2, "defaultName": "ネハン",
             "pvs": [self.TOPIC, self.REAL]},
            {**SONG_ITEM, "id": 3, "defaultName": "没有 PV 信息"},
        ]}
        with _patch_get({pt.VOCADB_SONG_URL: payload}):
            songs = pt.fetch_songs(23981)
        self.assertEqual(["ネハン", "没有 PV 信息"], [song.ja for song in songs])


