class InsertIntoPagesTest(unittest.TestCase):
    def test_insert_into_pages(self):
        texts = {"时滞记录": "正文\n\n{{P主|collapsed}}\n== 注释 ==\n<references/>\n",
                 "Navy": "正文\n\n{{雄之助}}\n== 注释 ==\n"}
        edited = []
        seen = []
        with mock.patch.object(pt.wiki_api, "fetch_pages_text", return_value=texts), \
                mock.patch.object(pt.wiki_api, "edit_page",
                                  side_effect=lambda title, text, summary="": edited.append(title)
                                  or {"ok": True}):
            results = pt.insert_into_pages("雄之助", ["时滞记录", "Navy", "不存在"], seen.append)
        self.assertEqual([r["title"] for r in results], ["时滞记录", "Navy", "不存在"])
        self.assertTrue(results[0]["ok"])
        self.assertEqual(results[1]["count"], 0)                 # 已经有了
        self.assertFalse(results[2]["ok"])
        self.assertEqual(edited, ["时滞记录"])
        self.assertEqual(len(seen), 3)

    def test_insert_into_pages_reports_edit_failure(self):
        with mock.patch.object(pt.wiki_api, "fetch_pages_text",
                               return_value={"A": "正文\n== 注释 ==\n"}), \
                mock.patch.object(pt.wiki_api, "edit_page",
                                  return_value={"ok": False, "error": "被权限挡住"}):
            results = pt.insert_into_pages("P主", ["A"])
        self.assertFalse(results[0]["ok"])
        self.assertIn("权限", results[0]["error"])


