class ProducerPageTest(unittest.TestCase):
    PAGE = """== 歌曲 ==
{{Producer_Song
|nnd_id   = sm45871877
|作曲     = {{lj|はるまきごはん}}
|投稿日期 = 2025年8月21日
|条目     = 揉揉头
|标题     = {{lj|アタマモミ}}
|image    = x.jpg
}}

{{Producer_Song
|条目     = 时滞记录
|标题     = {{lj|[[时滞记录|ラグタイムレコード]]}}
}}

* 专辑：《[[#Void|Void]]》与 [[#Pathos|Pathos]]
{{lj|[[银河录|{{lj|銀河録}}]]}}
"""

    # 歌曲条目一定带信息框（实测：VOCALOID Songbox / VOCALOID_Songbox）
    SONG_PAGE = "{{VOCALOID Songbox\n|标题 = ラグタイムレコード\n}}\n'''ラグタイムレコード''' 即时滞记录。"
    # 榜单页：正文写着歌名，但没有信息框 —— 不是歌曲条目（实测第 87 期用的就是 {{Billboard}}）
    RANKING_PAGE = ("{{Billboard|index=87}}\n{| class=\"wikitable\"\n|-\n"
                    "| 1 || [[ラグタイムレコード]] || はるまきごはん\n|}")

    def test_parse_producer_page(self):
        mapping = pt.parse_producer_page(self.PAGE)
        self.assertEqual(mapping["アタマモミ"], "揉揉头")
        self.assertEqual(mapping["ラグタイムレコード"], "时滞记录")
        self.assertEqual(mapping["銀河録"], "银河录")
        self.assertNotIn("Void", mapping)          # `[[#Void|Void]]` 是专辑小节，不是条目
        self.assertNotIn("Pathos", mapping)

    def test_apply_wiki_names(self):
        songs = [pt.ProducerSong(ja="アタマモミ"), pt.ProducerSong(ja="未知的歌"),
                 pt.ProducerSong(ja="アタマモミ", cn="已填的")]
        filled = pt.apply_wiki_names(songs, {"アタマモミ": "揉揉头"})
        self.assertEqual(filled, 1)
        self.assertEqual(songs[0].cn, "揉揉头")
        self.assertEqual(songs[2].cn, "已填的")     # 已经填过的不覆盖

    def test_merge_page_songs_adds_wiki_only_songs(self):
        work = pt.ProducerWork(songs=[pt.ProducerSong(ja="アタマモミ", date="2025-08-21")])
        pt._merge_page_songs(work, self.PAGE)
        names = [s.ja for s in work.songs]
        self.assertIn("ラグタイムレコード", names)          # 页面上有、VocaDB 没给
        self.assertEqual(names.count("アタマモミ"), 1)      # 重复的不再加一遍
        added = [s for s in work.songs if s.ja == "ラグタイムレコード"][0]
        self.assertEqual(added.source, "wiki")

    def test_mark_existing_fills_chinese_name(self):
        songs = [pt.ProducerSong(ja="ラグタイムレコード"), pt.ProducerSong(ja="不存在")]
        pt.mark_existing(songs, {"时滞记录": "正文"})
        self.assertFalse(songs[0].page_exists)
        pt.mark_existing([pt.ProducerSong(ja="タイトル")], {"タイトル": "正文"})
        songs = [pt.ProducerSong(ja="ラグタイムレコード", cn="时滞记录")]
        pt.mark_existing(songs, {"时滞记录": "正文"})
        self.assertTrue(songs[0].page_exists)

    def test_resolve_from_wiki(self):
        work = pt.ProducerWork(artist=pt.ProducerArtist(id=1, name="雄之助"),
                               songs=[pt.ProducerSong(ja="ラグタイムレコード"),
                                      pt.ProducerSong(ja="Navy")])
        texts = {"雄之助": self.PAGE, "时滞记录": "正文", "Navy": "正文"}
        with mock.patch.object(pt.wiki_api, "fetch_pages_text",
                               side_effect=lambda titles: {t: texts[t] for t in titles
                                                           if t in texts}):
            pt.resolve_from_wiki(work)
        self.assertEqual(work.page_name, "雄之助")
        by_ja = {song.ja: song for song in work.songs}
        self.assertEqual(by_ja["ラグタイムレコード"].cn, "时滞记录")
        self.assertEqual(by_ja["アタマモミ"].cn, "揉揉头")          # 从 P主条目里补进来的
        self.assertEqual(by_ja["アタマモミ"].date, "2025-08-21")   # 日期也来自 {{Producer_Song}}

    def test_search_page_by_song_prefers_page_with_japanese_name(self):
        result = [("雄之助", "别的"), ("时滞记录", self.SONG_PAGE)]
        with mock.patch.object(pt.wiki_api, "search_pages_with_text",
                               return_value=result):
            self.assertEqual(pt.search_page_by_song(pt.ProducerSong(ja="ラグタイムレコード")),
                             "时滞记录")
        with mock.patch.object(pt.wiki_api, "search_pages_with_text", return_value=[]):
            self.assertEqual(pt.search_page_by_song(pt.ProducerSong(ja="ラグタイムレコード")), "")

    def test_looks_like_song_page_needs_a_songbox(self):
        """歌曲条目都带 `{{…Songbox}}`；榜单页 / 专辑页 / P主页面 / 消歧义页都不带。"""
        self.assertTrue(pt.looks_like_song_page(self.SONG_PAGE))
        self.assertTrue(pt.looks_like_song_page("{{VOCALOID_Songbox\n|标题 = 时滞记录\n}}"))
        self.assertTrue(pt.looks_like_song_page("{{VOCALOID songbox}}"))     # 不区分大小写
        self.assertFalse(pt.looks_like_song_page(self.RANKING_PAGE))
        self.assertFalse(pt.looks_like_song_page("{{Album Infobox}}"))
        self.assertFalse(pt.looks_like_song_page("{{disambig}}"))
        self.assertFalse(pt.looks_like_song_page("{{Producer_Song|条目=随便}}"))
        self.assertFalse(pt.looks_like_song_page(""))
        self.assertFalse(pt.looks_like_song_page(None))

    def test_search_page_by_song_skips_pages_without_songbox(self):
        """用户 2026-10 报「中文名会变成 NICONICO VOCALOID SONGS TOP20/第87期」。

        实测那一页是 Billboard 榜单（用 `{{Billboard}}`），**正文里确实写着歌名**、
        可它没有 Songbox，不是歌曲条目 —— 以前只核对「正文提没提到日文名」，
        就把榜单页的标题当成中文条目名填进去了，模板最后还链到了榜单上。
        """
        ranking = ("NICONICO VOCALOID SONGS TOP20/第87期", self.RANKING_PAGE)
        with mock.patch.object(pt.wiki_api, "search_pages_with_text",
                               return_value=[ranking, ("时滞记录", self.SONG_PAGE)]):
            self.assertEqual(pt.search_page_by_song(pt.ProducerSong(ja="ラグタイムレコード")),
                             "时滞记录")
        with mock.patch.object(pt.wiki_api, "search_pages_with_text",
                               return_value=[ranking]):
            self.assertEqual(pt.search_page_by_song(pt.ProducerSong(ja="ラグタイムレコード")), "")

    def test_fill_missing_names(self):
        songs = [pt.ProducerSong(ja="已填", cn="已填"), pt.ProducerSong(ja="要找"),
                 pt.ProducerSong(ja="找不到")]
        seen = []
        with mock.patch.object(pt, "search_page_by_song",
                               side_effect=lambda song: "找到的页" if song.ja == "要找" else ""):
            filled = pt.fill_missing_names(songs, progress=seen.append)
        self.assertEqual(filled, 1)
        self.assertEqual(songs[1].cn, "找到的页")
        self.assertTrue(any("要找" in line for line in seen))


