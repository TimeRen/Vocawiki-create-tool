class _Response:
    def __init__(self, payload):
        self.text = json.dumps(payload) if not isinstance(payload, str) else payload
        self.status_code = 200

    def raise_for_status(self):
        return None


def _patch_get(routes):
    """按 url 前缀分发假响应；返回 mock 出来的 `http_get`。"""

    def fake_get(url, use_proxy=False, params=None, timeout=None, **kwargs):
        for prefix, payload in routes.items():
            if url.startswith(prefix):
                if callable(payload):
                    return _Response(payload(params or {}))
                return _Response(payload)
        raise AssertionError(f"没准备好这个地址的假响应：{url}")

    return mock.patch.object(pt, "http_get", side_effect=fake_get)


