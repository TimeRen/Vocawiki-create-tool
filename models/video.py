class VideoSite(Enum):
    NICO_NICO = "niconico"
    BILIBILI = "bilibili"
    YOUTUBE = "YouTube"


class Video:
    def __init__(self, site: VideoSite, identifier: str, url: str, views: int, uploaded: datetime,
                 thumb_url: str = None, canonical: bool = True, deleted: bool = False,
                 uploaded_cn: Optional[datetime] = None):
        self.site: VideoSite = site
        self.identifier: str = identifier
        self.url = url
        self.views: int = views
        self.uploaded: datetime = uploaded
        self.thumb_url: str = thumb_url
        self.canonical = canonical
        # 视频已被设为非公開 / 删除（数据来自 nicolog）：条目改用 {{VOCALOID Songbox/card}} 写投稿栏
        self.deleted = deleted
        # 投稿时刻（**东八区墙钟，保留到分钟**）：`uploaded` 被截断到日，而大家族模板列表的
        # 日期注释要精确到分钟（`<!-- 02-22 23:00 -->`）。工具其它地方（`|nnd_date` 等）也用
        # 东八区，所以这里不平移回日本时间：nico 的 `2024-02-23T00:00:00+09:00`
        # → 东八区 `2024-02-22 23:00`（实测模板里就是这么写的）。取不到就是 None。
        self.uploaded_cn: Optional[datetime] = uploaded_cn

    def __str__(self) -> str:
        return f"VideoSite: {self.site}\n" \
               f"Id: {self.identifier}\n" \
               f"Views: {self.views}\n" \
               f"Uploaded: {self.uploaded}\n" \
               f"Thumb: {self.thumb_url}\n\n"


TOPIC_AUTHOR_SUFFIX = " - Topic"
AUTO_UPLOAD_MARKERS = ("Provided to YouTube by", "Auto-generated by YouTube")


def is_auto_upload(pv: dict) -> bool:
    """Identify YouTube's distributor-generated Topic uploads."""
    author = str((pv or {}).get("author") or "")
    description = str((pv or {}).get("description") or "")
    return (author.rstrip().endswith(TOPIC_AUTHOR_SUFFIX)
            or any(marker in description for marker in AUTO_UPLOAD_MARKERS))


