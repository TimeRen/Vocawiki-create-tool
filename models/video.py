def video_from_site(site: VideoSite, identifier: str, canonical: bool = True) -> Union[Video, None]:
    """取一个站点的视频信息；偶发失败会重试 `FETCH_ATTEMPTS` 次。

    重试完仍失败时返回占位 Video（`views=0`、投稿日 epoch，由调用方用 VocaDB 的
    投稿日兜底），并**在日志里明确说出「荣誉题头会缺这一站」** —— 这种失败以前是静默的，
    条目里就只剩一个「明明该有、却不知为何没有」的题头。
    连视频 ID 都认不出来时（例如一条认不出 ID 的链接）返回 None：没有能写进模板的值。
    """
    logging.info('Fetching video from ' + site.value)
    logging.debug(f"Video identifier: {identifier}")
    v = None
    for attempt in range(1, FETCH_ATTEMPTS + 1):
        try:
            v = info_func[site](identifier)
            break
        except Exception as error:
            if attempt < FETCH_ATTEMPTS:
                logging.warning("%s 抓取失败（%s），%.1f 秒后重试（第 %d/%d 次）",
                                site.value, error, FETCH_RETRY_DELAY, attempt, FETCH_ATTEMPTS)
                time.sleep(FETCH_RETRY_DELAY)
                continue
            logging.warning(_("fail_fetch") + site.value)
            logging.exception("Failed to fetch %s: %s", site.value, error)
            logging.error("取不到 %s 的播放量：荣誉题头里不会有这一站的殿堂 / 传说，"
                          "投稿日改用 VocaDB 的记录。请检查网络或代理后重跑一次。", site.value)
    if not v:
        raw = identifier
        if site == VideoSite.YOUTUBE:
            identifier = parse_yt_url(identifier)
        elif site == VideoSite.BILIBILI:
            # 兜底也得是能写进 `|bb_id` 的 ID：整条链接写进去就是错的（见 `get_bv`）
            identifier = get_bv(identifier)
        else:
            identifier = parse_nc_url(identifier)
        if not identifier:
            # 连 ID 都认不出来（例如认不出的链接）：没有可写的值，整条跳过
            logging.warning("认不出 %s 的视频 ID：%s", site.value, raw)
            return None
        return Video(site, identifier, "", 0, datetime.fromtimestamp(0))
    v.canonical = canonical
    return v


def str_to_date(date: str) -> datetime:
    if 'T' in date:
        date = date[:date.find('T')]
    date = date.split("-")
    if len(date) != 3:
        logging.warning(_("invalid_date"))
        return datetime.fromtimestamp(0)
    year = int(date[0])
    month = int(date[1])
    day = int(date[2])
    return datetime(year=year, month=month, day=day)


BILIBILI_SEARCH_LIMIT = 20
# 标题 / 简介里的「搬运」信号。强信号直接判定不是官方投稿；弱信号只在 UP 主
# 不是 P主 时才这么判（P主 自己给官方稿加「中文字幕」不该被当成搬运）。
REPOST_STRONG_MARKERS = ("搬运", "搬運", "转载", "轉載", "転載", "转贴", "轉貼",
                        "补档", "補檔", "非官方", "侵删", "侵權即刪",
                        "授权转载", "授權轉載", "搬运自", "搬運自", "转载自", "轉載自")
REPOST_WEAK_MARKERS = ("字幕", "中字", "翻译", "翻譯", "熟肉", "本家", "原曲", "合集", "整合")
# 标题里出现这些词，说明是同一首歌的另一个编曲 / 版本，不是条目对应的原投稿。
# 只有当歌名本身也带同样的词时才不扣分（例如条目就是《Song (Remix)》）。
VERSION_MARKERS = ("remix", "re-mix", "リミックス", "リアレンジ",
                   "two-step mix", "two step mix", "two-step",
                   "アレンジ", "arrange", "acoustic", "acapella", "instrumental",
                   "off vocal", "offvocal", "カラオケ", "nightcore", "8bit",
                   "extended", "short ver", "short ver.", "mashup")
# 官方稿常写「禁止转载 / 请勿搬运」——那是**禁止**别人搬运，不能当成搬运标记
REPOST_FORBID_RE = re.compile(
    r"(?:(?:禁止|请勿|請勿|严禁|嚴禁|不得|未经许可|未經許可|未经授权|未經授權)"
    r"[^。\n]{0,16}(?:搬运|搬運|转载|轉載|転載)"
    r"|(?:搬运|搬運|转载|轉載|転載)[^。\n]{0,6}"
    r"(?:禁止|请勿|請勿|严禁|嚴禁|不得))")
# 简介里带着原稿链接 / sm 号，通常就是搬运说明
REPOST_LINK_RE = re.compile(
    r"nicovideo\.jp|youtube\.com|youtu\.be|piapro\.jp|twitter\.com|sm\d{4,}|nm\d{4,}",
    re.IGNORECASE)
COVER_MARKERS = ("歌ってみた", "翻唱", "翻唱版", "cover", "covered", "カバー")
# UP 主不是 P主 但明确写「官方投稿」的（厂牌 / 官方账号）：不算搬运，但仍交给人工确认
OFFICIAL_CLAIM_MARKERS = ("官方投稿", "官方账号", "官方上传", "本家投稿", "本人投稿",
                          "作者投稿", "P主投稿", "公式")
TITLE_TAG_RE = re.compile(r"<[^>]+>")


def _bili_text(value: object) -> str:
    """b 站搜索结果的标题带 `<em class="keyword">` 高亮，先去掉标签。"""
    return unescape(TITLE_TAG_RE.sub("", str(value or ""))).strip()


def _text_key(value: object) -> str:
    """名字 / 标题比对用的键：去掉空白与常见标点，统一大小写。"""
    text = re.sub(r"[\s\u3000_\-*＊.,，。・:：;；!！?？'\"“”‘’()（）\[\]【】<>《》]+",
                  "", str(value or ""))
    return text.casefold()


@dataclass
class BilibiliCandidate:
    bvid: str
    title: str
    author: str
    description: str = ""
    tag: str = ""
    play: int = 0
    repost: bool = False
    official: bool = False
    cover: bool = False
    alternate: str = ""
    original_link: bool = False
    score: int = 0


def _alternate_marker(title: str, name_keys: Sequence[str]) -> str:
    """标题里的「另一个版本」标记；歌名本身也有该标记时返回空串。"""
    title_key = _text_key(title)
    for marker in VERSION_MARKERS:
        marker_key = _text_key(marker)
        if marker_key and marker_key in title_key and \
                not any(marker_key in key for key in name_keys):
            return marker
    return ""


def _bilibili_candidate(item: dict, producer_keys: Sequence[str],
                        name_keys: Sequence[str] = ()) -> Optional[BilibiliCandidate]:
    bvid = str(item.get("bvid") or "").strip()
    if not bvid and item.get("aid"):
        try:
            bvid = av_to_bv(f"av{int(item['aid'])}")
        except (TypeError, ValueError):
            bvid = ""
    if not bvid:
        return None
    title = _bili_text(item.get("title"))
    description = _bili_text(item.get("description"))
    tag = _bili_text(item.get("tag"))
    author = _bili_text(item.get("author"))
    text = "\n".join((title, description, tag))
    marker_text = REPOST_FORBID_RE.sub("", text)
    author_official = bool(author) and any(
        len(key) >= 2 and key in _text_key(author) for key in producer_keys)
    strong_repost = any(marker in marker_text for marker in REPOST_STRONG_MARKERS)
    weak_repost = (any(marker in marker_text for marker in REPOST_WEAK_MARKERS)
                   or bool(REPOST_LINK_RE.search(marker_text)))
    official_claim = any(marker in marker_text for marker in OFFICIAL_CLAIM_MARKERS)
    repost = strong_repost or (weak_repost and not author_official and not official_claim)
    official = author_official and not strong_repost
    try:
        play = int(item.get("play") or 0)
    except (TypeError, ValueError):
        play = 0
    return BilibiliCandidate(
        bvid=bvid, title=title, author=author, description=description, tag=tag,
        play=play, repost=repost, official=official,
        cover=any(marker.casefold() in title.casefold() for marker in COVER_MARKERS),
        alternate=_alternate_marker(title, name_keys),
        original_link=bool(REPOST_LINK_RE.search(description)))


def _score_bilibili_candidate(candidate: BilibiliCandidate, name_keys: Sequence[str],
                              producer_keys: Sequence[str],
                              vocalist_keys: Sequence[str]) -> int:
    title_key, desc_key = _text_key(candidate.title), _text_key(candidate.description)
    author_key = _text_key(candidate.author)
    title_match = any(key and key in title_key for key in name_keys)
    desc_match = any(key and key in desc_key for key in name_keys)
    if not title_match:
        # 标题没写歌名、只在简介里提到时，必须同时能对上 P主，别把无关视频当成这首歌
        if not desc_match or not any(key and (key in desc_key or key in author_key)
                                     for key in producer_keys):
            return -99
    score = 5 if title_match else 2
    for key in producer_keys:
        if not key:
            continue
        if key in title_key:
            score += 2
        if key in author_key:
            score += 4
        if key in desc_key:
            score += 1
    score += sum(1 for key in vocalist_keys if key and key in title_key)
    if candidate.cover:
        score -= 4
    if candidate.alternate:
        score -= 6                       # Remix / Arrange / two-step mix 不是原投稿
    if candidate.repost:
        score -= 1                       # 同分时优先官方稿
    if candidate.official:
        score += 2
    if candidate.original_link:
        score += 1                       # 简介给出原稿链接，通常是这首歌的搬运稿
    # 播放量只用于同分排序（见 `_search_bilibili_candidates` 的 sort key），
    # 不计进分数：否则「Tears」之类热门但无关的视频会把真正的稿件挤出自动选择。
    return score


def _search_query_name(name: str) -> str:
    """B 站搜索不接受 `*tear*` 这种装饰符号：去掉它们再搜。"""
    return re.sub(r'[*＊"“”\'‘’]', "", str(name or "")).strip()


def _search_bilibili_candidates(name_ja: str, name_chs: str, producers: Sequence[str],
                                vocalists: Sequence[str]) -> List[BilibiliCandidate]:
    """按歌名搜 b 站，返回与这首歌相关、按可信度排好序的候选。"""
    from utils import producer_template       # 延迟导入：它会 import 本模块

    names = list(dict.fromkeys(name.strip() for name in (name_ja, name_chs)
                               if str(name or "").strip()))
    if not names:
        return []
    name_keys = [_text_key(name) for name in names]
    producer_keys = [_text_key(name) for name in producers if str(name or "").strip()]
    vocalist_keys = [_text_key(name) for name in vocalists if str(name or "").strip()]
    queries: List[str] = []
    for name in names:
        queries.append(name)
        clean = _search_query_name(name)
        if clean and clean != name:
            queries.append(clean)
    clean = _search_query_name(names[0])
    if producer_keys and producers and str(producers[0]).strip():
        producer = str(producers[0]).strip()
        # B 站搜索对「P主 + 歌名」的顺序和大小写敏感：`dateken tear` 能搜到
        # 「【鏡音リン】 *tear*」，`*tear* DATEKEN` 反而搜不到（用户 2026-10-18 报的）。
        queries.append(f"{clean} {producer}")
        queries.append(f"{producer.casefold()} {clean.casefold()}")
    if vocalists and str(vocalists[0]).strip():
        vocalist = str(vocalists[0]).strip()
        # 搜索排序会变，单靠 P主 有时把原稿挤出前 20；歌姬名 + 歌名能稳定搜到。
        queries.append(f"{vocalist} {clean}")
        queries.append(f"{clean} {vocalist}")
    queries = list(dict.fromkeys(query for query in queries if query.strip()))
    items: List[dict] = []
    for query in queries:
        try:
            items.extend(producer_template.bilibili_search_items(
                query, limit=BILIBILI_SEARCH_LIMIT))
        except Exception as e:                  # noqa: BLE001 - 搜索失败退回手动输入
            logging.warning("b 站搜索「%s」失败：%s", query, e)

    def collect(raw_items: List[dict], found: dict) -> None:
        for item in raw_items:
            candidate = _bilibili_candidate(item, producer_keys, name_keys)
            if candidate and candidate.bvid not in found:
                found[candidate.bvid] = candidate

    found: dict = {}
    collect(items, found)
    # 第一轮没看到搬运信号时，再专门搜一次「搬运 / 转载」；不额外增加太多请求
    if not any(candidate.repost for candidate in found.values()):
        for query in (f"{names[0]} 搬运", f"{names[0]} 转载"):
            try:
                collect(producer_template.bilibili_search_items(
                    query, limit=BILIBILI_SEARCH_LIMIT), found)
            except Exception as e:              # noqa: BLE001
                logging.warning("b 站搜索「%s」失败：%s", query, e)
    candidates: List[BilibiliCandidate] = []
    for candidate in found.values():
        score = _score_bilibili_candidate(candidate, name_keys, producer_keys, vocalist_keys)
        if score >= 0:
            candidate.score = score
            candidates.append(candidate)
    return sorted(candidates, key=lambda item: (-item.score, -item.play, item.title))


def _choose_bilibili_candidate(candidates: Sequence[BilibiliCandidate]) -> Optional[BilibiliCandidate]:
    """在候选里挑一个：差距明显就自动选；同分（拿不准）交给人工。

    返回 None 表示「候选都不是这首歌」—— 调用方会接着让用户手填链接（用户 2026-10-18 要求：
    点「都不是」之后还能把 b 站链接贴进来，而不是这一趟就没有 B 站稿件了）。
    """
    ranked = [candidate for candidate in candidates if not candidate.cover] or list(candidates)
    if not ranked:
        return None
    top = ranked[:3]
    if len(top) == 1 or top[0].score - top[1].score >= 2:
        return top[0]
    labels = [f"{item.title} — UP：{item.author}" for item in top]
    labels.append(_("bilibili_none"))
    index = prompt_choices(_("bilibili_choose"), labels)
    return None if index == len(labels) else top[index - 1]


def _prompt_bilibili_link(reason: str = "") -> Union[Video, None]:
    """搜索不到、或候选都不是时的退路：让用户手填链接 / BV 号。

    `reason` 是「候选都不是这首歌」那种说明，直接当问句用（已经写明「请粘贴链接」）；
    没给就用默认那句「b站投稿链接（或BV号）是？」。
    """
    bv = prompt_response(reason or _("bilibili_link"))
    if bv.isspace() or len(bv) == 0:
        return None
    bv = resolve_short_link(bv) or bv          # b23.tv 短链先换成真实链接
    bv_canonical = prompt_choices(_("bv_canonical"), [_("Yes"), _("No")])
    return video_from_site(VideoSite.BILIBILI, bv, bv_canonical == 1)


def get_video_bilibili(name_ja: str = "", name_chs: str = "",
                       producers: Sequence[str] = (),
                       vocalists: Sequence[str] = ()) -> Union[Video, None]:
    """B 站稿件：先自动搜索，再判断是不是搬运 / 官方投稿。

    搜到多个同样可信的候选、或者「搬不搬运」看不出来时，才交给人工判断；
    搜索结果里明确带「搬运 / 转载 / 补档」等字样的，直接按非官方投稿处理。
    完全没搜到时退回「手填链接」，与旧流程一致。
    """
    try:
        candidates = _search_bilibili_candidates(name_ja, name_chs, producers, vocalists)
    except Exception as e:                          # noqa: BLE001 - 搜不了就退回手填
        logging.warning("b 站搜索失败，改为手动输入链接：%s", e)
        return _prompt_bilibili_link()
    if not candidates:
        logging.info("b 站没搜到「%s」的相关视频，改为手动输入链接", name_ja or name_chs)
        return _prompt_bilibili_link()
    chosen = _choose_bilibili_candidate(candidates)
    if chosen is None:
        # 候选都不是这首（或用户点了「都不是」）：让用户把链接贴进来
        logging.info("b 站搜到的候选都不是「%s」，改为手动输入链接", name_ja or name_chs)
        return _prompt_bilibili_link(_("bilibili_none_link"))
    if chosen.repost:
        logging.info("b 站视频「%s」含搬运 / 转载标记，按非官方投稿处理", chosen.title)
        canonical = False
    elif chosen.official:
        logging.info("b 站视频「%s」的 UP 主与 P主 匹配，按官方投稿处理", chosen.title)
        canonical = True
    else:
        canonical = prompt_choices(
            _("bilibili_canonical_video").format(title=chosen.title, author=chosen.author),
            [_("Yes"), _("No")]) == 1
    return video_from_site(VideoSite.BILIBILI, chosen.bvid, canonical)


# 用户手输的链接（或裸 ID）分别长什么样
NICO_LINK_RE = re.compile(r"nicovideo\.jp|^s[mo]\d+$", re.IGNORECASE)
# B 站短链：只有短码，必须联网跳转后才能拿到 BV 号
SHORT_LINK_HOSTS = ("b23.tv", "bili2233.cn")
SHORT_LINK_RE = re.compile(r"b23\.tv|bili2233\.cn", re.IGNORECASE)
BILIBILI_LINK_RE = re.compile(r"bilibili\.com|^av\d+$", re.IGNORECASE)
BV_ID_RE = re.compile(r"^BV[0-9A-Za-z]+$", re.IGNORECASE)
YOUTUBE_LINK_RE = re.compile(r"youtu\.?be", re.IGNORECASE)
YOUTUBE_ID_RE = re.compile(r"^[A-Za-z0-9_-]{11}$")


def short_link_url(link: str) -> Optional[str]:
    """链接是 B 站短链时返回补好协议的完整 URL，否则返回 None。"""
    text = (link or "").strip()
    if not text:
        return None
    url = text if "://" in text else "https://" + text
    if (urlparse(url).hostname or "").lower() not in SHORT_LINK_HOSTS:
        return None
    return url


def resolve_short_link(link: str) -> Optional[str]:
    """B 站短链（b23.tv / bili2233.cn）→ 真实链接；不是短链或跳转失败时返回 None。

    实测 <https://b23.tv/Zt8UWvS> → 302 Location: https://www.bilibili.com/video/BV1fc386VE6n?…，
    所以只发一个不跟随跳转的请求读 Location，不把整个视频页拉下来。
    （图文 / 笔记会跳到 m.bilibili.com/opus/…，不是视频，留给后面的 BV 号校验拒掉。）
    """
    url = short_link_url(link)
    if url is None:
        return None
    try:
        response = http_get(url, use_proxy=False,
                            timeout=REQUEST_TIMEOUT, allow_redirects=False)
    except Exception as e:                      # 短链解析失败不影响提示重输
        logging.warning("无法解析B站短链 %s：%s", url, e)
        return None
    location = (response.headers.get("Location") or "").strip()
    if not location:
        logging.warning("B站短链 %s 没有跳转地址（HTTP %s）", url, response.status_code)
        return None
    logging.info("B站短链 %s → %s", url, location)
    return location


