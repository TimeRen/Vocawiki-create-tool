CN_TIMEZONE = timezone(timedelta(hours=8))


def nico_date_to_cn(date: str) -> datetime:
    """将niconico返回的ISO时间(东九区)转换为东八区的日期。"""
    try:
        dt = datetime.fromisoformat(date)
    except ValueError:
        return str_to_date(date)
    if dt.tzinfo is None:
        return dt
    dt = dt.astimezone(CN_TIMEZONE)
    return datetime(year=dt.year, month=dt.month, day=dt.day)


def nico_uploaded_cn(date: str) -> Optional[datetime]:
    """niconico 的 `uploadDate`（带 `+09:00`）→ **东八区墙钟**（保留到分钟）；认不出返回 None。

    `nico_date_to_cn` 只给到日；大家族模板列表的日期注释要分钟（`<!-- 02-22 23:00 -->`），
    实测就写东八区的时刻（nico 的 `2024-02-23T00:00:00+09:00` ↔ 注释 `02-22 23:00`），
    与工具其它地方的时区口径一致。
    """
    try:
        dt = datetime.fromisoformat(date)
    except (TypeError, ValueError):
        return None
    if dt.tzinfo is None:
        return dt
    return dt.astimezone(CN_TIMEZONE).replace(tzinfo=None)


def is_player_thumbnail(url: str) -> bool:
    """这个地址是不是 niconico 的**播放器截图**（正中间烙着一个播放键，不能当封面）。

    2026-10-20 实测：niconico 的 `og:image` 换成了
    `https://goptim.video.nimg.jp/thumbnail/1280x720?b=p&bs=54&i=…&s=blur&key=…` ——
    那是一帧播放器画面，中间一个白色播放键，直接拿来当封面就是用户报的
    「OGP 图像都带一个图案」。同一页里还给了干净封面（`img.cdn.nimg.jp/s/…`）。
    """
    text = str(url or "")
    return any(marker in text for marker in PLAYER_THUMBNAIL_MARKERS)


def get_nc_thumbnail(soup) -> Optional[str]:
    """取 niconico 封面：**跳过播放器截图**，优先用页面里另外给的干净缩略图。

    候选顺序：`og:image` / `twitter:image` / `thumbnail` → `<link rel=preload as=image>`
    （实测是 `img.cdn.nimg.jp/s/nicovideo/thumbnails/<id>/<id>.<hash>.original/a960x540l`）
    → 内嵌 JSON 里的 `"thumbnailUrl": ["…", "…"]`。一个干净的都没有时返回 None
    —— 宁可这一路没有封面，也别往条目里塞一张带播放键的图。
    """
    candidates: List[str] = []
    for attrs in ({"property": "og:image"},
                  {"name": "twitter:image"},
                  {"name": "thumbnail"}):
        meta = soup.find("meta", attrs)
        if meta and meta.get("content"):
            candidates.append(str(meta["content"]))
    for link in soup.find_all("link", {"as": "image"}):
        if link.get("href"):
            candidates.append(str(link["href"]))
    for script in soup.find_all("script"):
        text = script.get_text() or ""
        for match in re.finditer(r'"thumbnailUrl"\s*:\s*\[([^\]]*)\]', text):
            for part in re.findall(r'"([^"]+)"', match.group(1)):
                candidates.append(part.replace("\\/", "/"))
    for url in candidates:
        if url and not is_player_thumbnail(url):
            return url
    if candidates:
        logging.warning("niconico 页面只给了播放器截图当封面（带播放键），这一张不用：%s",
                        candidates[0])
    return None


def get_nc_info(vid: str) -> Video:
    """取 niconico 视频信息；视频非公開 / 被删时改用 nicolog 的记录（见 utils/nicolog.py）。"""
    vid = parse_nc_url(vid)
    url = f"https://www.nicovideo.jp/watch/{vid}"
    page = _fetch_nc_page(vid, url)
    if page.gone:
        # 页面明确说这个稿件看不了 → 用 nicolog 的最后记录，并标成「已删除」
        archived = nicolog.fetch(vid)
        if archived is not None:
            logging.info("niconico %s 非公開 / 已删除，改用 nicolog 的数据（投稿日 %s，播放 %s）",
                         vid, archived.uploaded, archived.views)
            return Video(VideoSite.NICO_NICO, vid, url, archived.views,
                         archived.uploaded or page.date, archived.thumbnail or None, deleted=True)
        logging.warning("niconico %s 看不了（%s），nicolog 也没有记录", vid, page.reason)
        return Video(VideoSite.NICO_NICO, vid, url, 0, page.date)
    if page.readable:
        return Video(VideoSite.NICO_NICO, vid, url, page.views, page.date,
                     page.thumbnail, uploaded_cn=page.uploaded_cn)
    # 页面里既没有视频信息、也没有「看不了」的证据（被 Cloudflare 挡了一下 / 限流 / 空响应）：
    # 这**不是**删除。以前这种情况被当成删除，条目里就冒出 `class=deleted` 与「最终记录」
    # （用户 2026-10-21 报《Short Hand》：sm41926089 明明还在，却被标成 niconico 稿件被删）。
    archived = nicolog.fetch(vid)
    if archived is not None:
        logging.warning("niconico %s 这次没抓到页面（%s），播放量 / 投稿日改用 nicolog 的记录；"
                        "条目里**不会**标成已删除。若数字不对，请重跑一次。",
                        vid, page.reason)
        return Video(VideoSite.NICO_NICO, vid, url, archived.views,
                     archived.uploaded or page.date, archived.thumbnail or None,
                     uploaded_cn=page.uploaded_cn)
    logging.warning("niconico %s 这次没抓到页面（%s），也没有 nicolog 记录："
                    "荣誉题头会缺这一站的播放量。请检查网络或代理后重跑一次。", vid, page.reason)
    return Video(VideoSite.NICO_NICO, vid, url, 0, page.date)


@dataclass
class NicoPage:
    """一次 niconico watch 页面的抓取结果（`get_nc_info` 用它区分「看不了」与「没抓到」）。"""

    date: datetime = field(default_factory=lambda: datetime.fromtimestamp(0))
    uploaded_cn: Optional[datetime] = None
    views: int = 0
    thumbnail: Optional[str] = None
    # 页面里确实有视频信息（`uploadDate`）→ 稿件还在
    readable: bool = False
    # 页面明确说这个稿件看不了（已删除 / 非公開）→ 可以去 nicolog 取最后记录
    gone: bool = False
    # 给日志看的一句话
    reason: str = ""


# niconico 说「这个稿件看不了」的两条硬证据（2026-10-22 实测）：
#   非公開 → HTTP 403 + `"reasonCode":"HIDDEN_VIDEO"`；已删除 → HTTP 404 + `"reasonCode":"NOT_FOUND"`。
# 还在的稿件是 200 + `uploadDate`，页面上**不会**出现 `reasonCode`；
# 被 Cloudflare 挡住 / 限流时两样都没有 —— 那种情况只能算「没抓到」。
NC_GONE_STATUS = (404, 410)
NC_GONE_MARKER = "reasonCode"
NC_PAGE_ATTEMPTS = 2
NC_PAGE_RETRY_DELAY = 1.5


def _status_of(response) -> int:
    """响应的 HTTP 状态码（测试里的假响应没有这个属性，按 200 算）。"""
    try:
        return int(getattr(response, "status_code", 200) or 200)
    except (TypeError, ValueError):
        return 200


def _is_gone_page(status: int, text: str) -> bool:
    """这一页是不是在说「稿件已删除 / 非公開」。"""
    return status in NC_GONE_STATUS or NC_GONE_MARKER in (text or "")


def _read_nc_page(text: str, status: int) -> NicoPage:
    """从 watch 页面里读视频信息；读不到时区分「看不了」与「没抓到」。"""
    soup = BeautifulSoup(text or "", "html.parser")
    page = NicoPage(thumbnail=get_nc_thumbnail(soup))
    for script in soup.find_all('script'):
        t: str = script.get_text()
        match = re.search(r'"uploadDate"\s*:\s*"([^"]+)"', t)
        if match:
            page.date = nico_date_to_cn(match.group(1))
            page.uploaded_cn = nico_uploaded_cn(match.group(1))
            page.readable = True
        index_start = t.find("userInteractionCount")
        if index_start != -1:
            index_start += len("userInteractionCount") + 2
            index_end = t.find("}", index_start)
            page.views = int(t[index_start:index_end])
    if page.readable:
        page.reason = f"HTTP {status}"
    elif _is_gone_page(status, text):
        page.gone = True
        page.reason = f"HTTP {status}，页面说稿件看不了"
    else:
        page.reason = f"HTTP {status}，页面里没有视频信息"
    return page


def _fetch_nc_page(vid: str, url: str) -> NicoPage:
    """取 watch 页面并读数；「没抓到」时重试几次（HTTP 抖动 / 被挡一下很常见）。"""
    page = NicoPage()
    for attempt in range(1, NC_PAGE_ATTEMPTS + 1):
        response = http_get(url, use_proxy=True, timeout=REQUEST_TIMEOUT)
        page = _read_nc_page(getattr(response, "text", "") or "", _status_of(response))
        if page.readable or page.gone:
            return page
        if attempt < NC_PAGE_ATTEMPTS:
            logging.warning("niconico %s 第 %d 次没抓到页面（%s），%.1f 秒后重试",
                            vid, attempt, page.reason, NC_PAGE_RETRY_DELAY)
            time.sleep(NC_PAGE_RETRY_DELAY)
    return page


BILIBILI_VIEW_API = "https://api.bilibili.com/x/web-interface/view"
AV_ID_RE = re.compile(r"av\d+", re.IGNORECASE)


def get_bv(vid: str) -> str:
    """链接 / BV 号 / av 号 → 能写进 `|bb_id` 的 ID。

    有 BV 号就取 BV 号；旧 av 号换算成 BV 号；换算不了的新 av 号原样保留成 `av…`
    —— 站上的 `{{BilibiliVideo}}` 认这种写法（见 `Module:BilibiliVideoIDValidator`），
    **绝不能把整条链接**写进 `|bb_id`（实测 Secret Iris 就被写成了
    `|bb_id = https://www.bilibili.com/video/av114630730975233`）。
    """
    text = str(vid or "").strip()
    search_bv = re.search(r"BV[0-9A-Za-z]{10}", text, re.IGNORECASE)
    if search_bv is not None:
        return search_bv.group(0)
    search_av = re.search(r"\bav(\d+)", text, re.IGNORECASE)
    if search_av is not None:
        av = f"av{search_av.group(1)}"
        try:
            return av_to_bv(av)
        except ValueError:
            return av
    if "://" in text or "/" in text:
        # 认不出 ID 的链接：宁可空着，也不要把整条链接写进 |bb_id
        return ""
    return text


def get_bb_info(vid: str) -> Video:
    key = get_bv(vid)
    if AV_ID_RE.fullmatch(key):
        # 新 av 号算不出 BV 号，用 `aid` 问接口，接口会把真实 BV 号带回来
        url = f"{BILIBILI_VIEW_API}?aid={key[2:]}"
    elif re.fullmatch(r"BV[0-9A-Za-z]+", key, re.IGNORECASE):
        url = f"{BILIBILI_VIEW_API}?bvid={key}"
    else:
        raise ValueError(f"认不出 B 站视频 ID：{vid}")
    response = http_get(url, use_proxy=False,
                        timeout=REQUEST_TIMEOUT)
    response.raise_for_status()
    payload = response.json()
    if payload.get('code') != 0 or not payload.get('data'):
        raise ValueError(f"Bilibili API error: {payload.get('code')} {payload.get('message', '')}")
    data = payload['data']
    epoch_time = int(data['pubdate'])
    date = datetime.fromtimestamp(epoch_time)
    # remove extra information to be in sync with YT and Nico
    date = datetime(year=date.year, month=date.month, day=date.day)
    pic = data['pic']
    views = data['stat']['view']
    # 用接口返回的 BV 号：传进来的是 av 号时，这才是条目里该写的那个
    bvid = str(data.get('bvid') or key)
    return Video(VideoSite.BILIBILI, bvid, url, views, date, pic)


def parse_yt_url(vid: str) -> str:
    vid = vid.strip()
    if not vid:
        return vid
    if re.fullmatch(r"[A-Za-z0-9_-]{11}", vid):
        return vid
    parsed = urlparse(vid if "://" in vid else "https://" + vid)
    if parsed.hostname in {"youtu.be", "www.youtu.be"}:
        return parsed.path.strip("/").split("/")[0]
    if parsed.hostname and parsed.hostname.endswith("youtube.com"):
        if parsed.path == "/watch":
            return parse_qs(parsed.query).get("v", [""])[0]
        if parsed.path.startswith("/shorts/") or parsed.path.startswith("/embed/"):
            return parsed.path.split("/")[2]
    return vid


def _int_or_none(value) -> Optional[int]:
    """把页面里的计数转成 int（可能是 '1,234' 这种带分隔符的字符串）。"""
    try:
        return int(str(value).replace(",", "").strip())
    except (TypeError, ValueError):
        return None


def parse_yt_view_count(soup) -> Optional[int]:
    """YouTube 页面的播放量；认不出来返回 None。

    页面上有多个 interactionStatistic 块（实测 2026-09：第一条是 LikeAction
    **点赞数**，第二条才是 WatchAction 播放量），所以必须按 interactionType 挑。
    直接取第一个 `meta[itemprop="userInteractionCount"]` 会误把点赞当播放量，
    导致「明明是殿堂曲却没有荣誉题头」。
    """
    others: List[int] = []
    for block in soup.find_all(attrs={"itemprop": "interactionStatistic"}):
        count = block.find("meta", attrs={"itemprop": "userInteractionCount"})
        value = _int_or_none(count.get("content") if count is not None else None)
        if value is None:
            continue
        kind = block.find("meta", attrs={"itemprop": "interactionType"})
        if kind is not None and "WatchAction" in (kind.get("content") or ""):
            return value                                     # 播放量
        others.append(value)
    legacy = soup.find("meta", attrs={"itemprop": "interactionCount"})   # 旧版页面的裸计数
    value = _int_or_none(legacy.get("content") if legacy is not None else None)
    if value is not None:
        return value
    # 页面改版、认不出 WatchAction 时退回**最大的**那个计数：播放量永远大于点赞 / 收藏 /
    # 评论，取最大至少不会像旧实现那样把点赞当播放（2026-09 的「殿堂曲没有荣誉题头」）。
    return max(others) if others else None


def ld_json_video_object(soup) -> Optional[dict]:
    """页面 ld+json 里的 VideoObject；取不到返回 None。"""
    for script in soup.select('script[type="application/ld+json"]'):
        try:
            candidate = json.loads(script.string or script.get_text())
        except (TypeError, json.JSONDecodeError):
            continue
        items = candidate if isinstance(candidate, list) else [candidate]
        metadata = next((item for item in items
                         if isinstance(item, dict) and item.get('@type') == 'VideoObject'), None)
        if metadata:
            return metadata
    return None


def ld_json_view_count(metadata: dict) -> Optional[int]:
    """ld+json 里的播放量：VideoObject.interactionCount 最优先，
    其次 interactionStatistic 里 WatchAction 的那一条，都没有才退回第一个计数。"""
    direct = _int_or_none(metadata.get('interactionCount'))
    if direct is not None:
        return direct
    statistics = metadata.get('interactionStatistic') or []
    if isinstance(statistics, dict):
        statistics = [statistics]
    counts: List[int] = []
    for statistic in statistics:
        if not isinstance(statistic, dict):
            continue
        value = _int_or_none(statistic.get('userInteractionCount'))
        if value is None:
            continue
        kind = statistic.get('interactionType')
        kind = kind.get('@type') if isinstance(kind, dict) else kind
        if isinstance(kind, str) and "WatchAction" in kind:
            return value
        counts.append(value)
    # 同 parse_yt_view_count：认不出 WatchAction 时退回最大的计数（播放量最大）
    return max(counts) if counts else None


def get_yt_info(vid: str) -> Union[Video, None]:
    vid = parse_yt_url(vid)
    if not re.fullmatch(r"[A-Za-z0-9_-]{11}", vid):
        raise ValueError(f"Invalid YouTube video ID: {vid}")
    url = 'https://www.youtube.com/watch?v=' + vid
    response = http_get(url, use_proxy=True, timeout=REQUEST_TIMEOUT)
    response.raise_for_status()
    soup = BeautifulSoup(response.text, "html.parser")
    views = parse_yt_view_count(soup)
    published = soup.select_one('meta[itemprop="datePublished"][content]')
    if views is not None and published is not None:
        date = str_to_date(published['content'])
    else:
        metadata = ld_json_video_object(soup) or {}
        if views is None:
            views = ld_json_view_count(metadata)
        upload_date = metadata.get('uploadDate')
        if views is None or not upload_date:
            raise ValueError("YouTube page does not contain video metadata")
        date = str_to_date(upload_date)
    return Video(VideoSite.YOUTUBE, vid, url, views, date,
                 thumb_url="https://img.youtube.com/vi/{}/maxresdefault.jpg".format(vid))


